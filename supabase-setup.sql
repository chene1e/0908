create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 20),
  avatar text,
  score integer not null default 0 check (score >= 0),
  created_at timestamptz not null default now()
);

alter table public.game_scores enable row level security;

drop policy if exists "Anyone can view game scores" on public.game_scores;
create policy "Anyone can view game scores"
on public.game_scores for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can submit game scores" on public.game_scores;
create policy "Anyone can submit game scores"
on public.game_scores for insert
to anon, authenticated
with check (
  char_length(name) between 1 and 20
  and score >= 0
  and (avatar is null or char_length(avatar) <= 2200000)
);

grant select, insert on public.game_scores to anon, authenticated;
grant usage, select on sequence public.game_scores_id_seq to anon, authenticated;
