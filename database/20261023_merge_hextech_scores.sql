create table if not exists public.merge_hextech_scores (
  id bigint generated by default as identity primary key,
  run_id uuid not null unique,
  player_id uuid,
  name text not null check (char_length(name) between 1 and 40),
  avatar text not null default '' check (char_length(avatar) <= 2200000),
  score integer not null check (score >= 0),
  merge_count integer not null default 0 check (merge_count >= 0),
  highest_level smallint not null default 1 check (highest_level between 1 and 9),
  augments jsonb not null default '[]'::jsonb check (jsonb_typeof(augments) = 'array'),
  created_at timestamptz not null default now()
);

create index if not exists merge_hextech_scores_ranking_idx
  on public.merge_hextech_scores (score desc, created_at asc);

alter table public.merge_hextech_scores enable row level security;

revoke all on table public.merge_hextech_scores from anon, authenticated;
grant select, insert on table public.merge_hextech_scores to anon, authenticated;
grant all on table public.merge_hextech_scores to service_role;
grant usage, select on sequence public.merge_hextech_scores_id_seq to anon, authenticated, service_role;

drop policy if exists "Public can read merge hextech scores" on public.merge_hextech_scores;
create policy "Public can read merge hextech scores"
  on public.merge_hextech_scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can submit merge hextech scores" on public.merge_hextech_scores;
create policy "Public can submit merge hextech scores"
  on public.merge_hextech_scores for insert
  to anon, authenticated
  with check (
    char_length(name) between 1 and 40
    and char_length(avatar) <= 2200000
    and score >= 0
    and merge_count >= 0
    and highest_level between 1 and 9
    and jsonb_typeof(augments) = 'array'
  );
